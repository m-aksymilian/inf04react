// Regenerates .vscode/inf04_react.code-snippets AND 2_BUILDING_BLOCKS/README.md from the //@ blocks.
// Run from the repo root:  node 4_TOOLS/gen-snippets.mjs
// In VS Code (inside App.jsx):
//   form03  + Tab  -> the block's state + functions   (type it ABOVE App's return)
//   form03j + Tab  -> the block's JSX                  (type it INSIDE App's return)
//   js05 / comp01  -> plain helper / child component, inserted whole
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseBlocks } from '../9_VIEWER_AND_TESTS/viewer/parseBlocks.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, '2_BUILDING_BLOCKS');
const scope = 'javascriptreact,javascript';
const snippets = {};
const escape = (text) => text.split('\n').map((line) => line.replace(/\$/g, '\\$'));   // $ is a tabstop in snippets

const katalog = ['# Building blocks – catalog', '',
  'Generated by `node 4_TOOLS/gen-snippets.mjs`. Do not edit by hand. For live demos with Copy buttons, run `npm run dev` and open the index.', '',
  'VS Code snippets, typed inside App.jsx:',
  '- `form03` + Tab inserts the **logic** (state + functions). Type it above App\'s `return`.',
  '- `form03j` + Tab inserts the **JSX**. Type it inside App\'s `return`.',
  '- JS / COMP blocks (`js05`, `comp01`) are inserted whole.',
  '- Extras: `inf04app` (whole App.jsx), `fg` (form-group + input), `us` (useState), `mapli` (map → li).', ''];

for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.jsx')).sort()) {
  katalog.push(`## ${file}`, '', '| ID | snippets | what | needs |', '|---|---|---|---|');
  for (const b of parseBlocks(fs.readFileSync(path.join(dir, file), 'utf8'))) {
    const p = b.id.replace('-', '').toLowerCase();
    const needs = b.needs && b.needs !== '-' ? ' | needs ' + b.needs : '';
    if (b.logic !== null) {
      // component block -> two snippets, so nothing creates a second component inside App
      if (b.logic !== '') {
        snippets[`${b.id} logic`] = {
          scope, prefix: [p, b.id],
          description: `${b.description} – LOGIC (above return)${needs}`,
          body: [`// ${b.id} ${b.description}`, ...escape(b.logic)],
        };
      }
      snippets[`${b.id} JSX`] = {
        scope, prefix: b.logic !== '' ? [p + 'j'] : [p, p + 'j', b.id],
        description: `${b.description} – JSX (inside return)`,
        body: escape(b.jsx),
      };
      katalog.push(`| ${b.id} | ${b.logic !== '' ? `\`${p}\` + ` : ''}\`${p}j\` | ${b.description.replace(/\|/g, '\\|')} | ${b.needs} |`);
    } else {
      snippets[b.id] = {
        scope, prefix: [p, b.id],
        description: `${b.description}${needs} (${file})`,
        body: escape(b.code),
      };
      katalog.push(`| ${b.id} | \`${p}\` | ${b.description.replace(/\|/g, '\\|')} | ${b.needs} |`);
    }
  }
  katalog.push('');
}
fs.writeFileSync(path.join(dir, 'README.md'), katalog.join('\n'));

// exam skeletons. ${1/(.*)/${1:/capitalize}/} = the setter name is filled from the state name you type
const setter = (n) => `set\${${n}/(.*)/\${1:/capitalize}/}`;
snippets['INF04 App skeleton'] = {
  scope,
  prefix: ['inf04app'],                         // NOT "app": it would fire while typing "export default App"
  description: 'Whole App.jsx: imports, one component, form with onSubmit',
  body: [
    "import { useState } from 'react';",
    "import 'bootstrap/dist/css/bootstrap.css';",
    "import './App.css';",
    '',
    'function App() {',
    `  const [\${1:pole}, ${setter(1)}] = useState('');`,
    '',
    '  function ${2:zapisz}(e) {',
    '    e.preventDefault();',
    '    console.log($1);',
    '  }',
    '',
    '  return (',
    '    <div className="container">',
    '      <h1>${3:Tytuł}</h1>',
    '      <form onSubmit={$2}>',
    '        $0',
    '      </form>',
    '    </div>',
    '  );',
    '}',
    '',
    'export default App;',
  ],
};
snippets['INF04 form-group input'] = {
  scope,
  prefix: ['fg', 'formgroup'],
  description: 'form-group + label htmlFor + controlled input (id = state name)',
  body: [
    '<div className="form-group mb-3">',
    '  <label htmlFor="${1:pole}">${2:Etykieta:}</label>',
    '  <input',
    '    type="${3|text,number,password,email,date|}"',
    '    className="form-control"',
    '    id="$1"',
    '    value={$1}',
    `    onChange={(e) => ${setter(1)}(e.target.value)}`,
    '  />',
    '</div>',
  ],
};
snippets['INF04 useState'] = {
  scope,
  prefix: ['us', 'usestate'],
  description: 'const [x, setX] = useState() – setter filled automatically',
  body: [`const [\${1:stan}, ${setter(1)}] = useState(\${2:''});`],
};
snippets['INF04 map li'] = {
  scope,
  prefix: ['mapli'],
  description: '{tab.map(el => <li key>)}',
  body: ['{${1:tablica}.map((${2:el}) => (', '  <li key={$2}>{$2}</li>', '))}'],
};

fs.mkdirSync(path.join(root, '.vscode'), { recursive: true });
const out = path.join(root, '.vscode', 'inf04_react.code-snippets');
fs.writeFileSync(out, JSON.stringify(snippets, null, 2) + '\n');
console.log(`${Object.keys(snippets).length} snippets -> ${path.relative(root, out)}`);
